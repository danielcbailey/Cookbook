func randEmbedding(rng *rand.Rand, dims int) []float32 {
	v := make([]float32, dims)
	for i := range v {
		v[i] = rng.Float32()*2 - 1
	}
	return v
}

func BenchmarkListRecipesBySemanticSimilarity_1000(b *testing.B) {
	const numRecipes = 1000
	const dims = 1536

	db, err := local.NewLocal(b.TempDir())
	if err != nil {
		b.Fatal(err)
	}

	tx, err := db.NewTransaction(context.Background())
	if err != nil {
		b.Fatal(err)
	}

	u := models.User{Email: "bench@test.com", PasswordHash: "h"}
	if _, err := tx.CreateUser(&u); err != nil {
		b.Fatal(err)
	}

	rng := rand.New(rand.NewPCG(42, 0))
	for i := 0; i < numRecipes; i++ {
		r := models.Recipe{
			UserID:    u.ID,
			Title:     "Recipe",
			Embedding: randEmbedding(rng, dims),
		}
		if _, err := tx.CreateRecipe(&r); err != nil {
			b.Fatal(err)
		}
	}

	if err := tx.Commit(); err != nil {
		b.Fatal(err)
	}

	query := randEmbedding(rng, dims)

	b.ResetTimer()
	for b.Loop() {
		tx, err := db.NewTransaction(context.Background())
		if err != nil {
			b.Fatal(err)
		}
		results, err := tx.ListRecipesBySemanticSimilarity(u.ID, query, 10)
		if err != nil {
			b.Fatal(err)
		}
		if len(results) != 10 {
			b.Fatalf("got %d results, want 10", len(results))
		}
		tx.Rollback()
	}
}
