func setupRecipeTest(t *testing.T) (database.Transaction, models.User) {
	t.Helper()
	db, err := local.NewLocal(t.TempDir())
	if err != nil {
		t.Fatal(err)
	}
	tx, err := db.NewTransaction(t.Context())
	if err != nil {
		t.Fatal(err)
	}
	t.Cleanup(func() { tx.Rollback() })

	u := testUser()
	if _, err := tx.CreateUser(&u); err != nil {
		t.Fatal(err)
	}
	return tx, u
}

